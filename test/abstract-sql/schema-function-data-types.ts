import * as AbstractSQLCompiler from '../../out/abstract-sql-compiler.js';
import { expect } from 'chai';

// `Boolean` uses a type function for every engine, as does `Serial` for mysql/websql
const generateModel = (): AbstractSQLCompiler.AbstractSqlModel => ({
	synonyms: {},
	relationships: {},
	tables: {
		test: {
			name: 'test',
			resourceName: 'test',
			idField: 'id',
			fields: [
				{
					fieldName: 'id',
					dataType: 'Serial',
					required: true,
					index: 'PRIMARY KEY',
					checks: [['GreaterThan', ['Field', 'id'], ['Number', 0]]],
				},
				{
					fieldName: 'with default',
					dataType: 'Boolean',
					required: true,
					defaultValue: 'TRUE',
				},
				{
					fieldName: 'without default',
					dataType: 'Boolean',
					required: true,
				},
				{
					fieldName: 'with check',
					dataType: 'Boolean',
					checks: [['Equals', ['Field', 'with check'], ['Boolean', false]]],
				},
			],
			indexes: [],
			primitive: false,
		},
	},
	rules: [],
	lfInfo: { rules: {} },
});

describe('data types generated by a type function', () => {
	it('should use the default value and checks on postgres', () => {
		expect(AbstractSQLCompiler.postgres.compileSchema(generateModel()))
			.to.have.property('createSchema')
			.that.deep.equals([
				`\
CREATE TABLE IF NOT EXISTS "test" (
	"id" SERIAL NOT NULL CHECK ("id" > 0) PRIMARY KEY
,	"with default" BOOLEAN DEFAULT TRUE NOT NULL
,	"without default" BOOLEAN DEFAULT FALSE NOT NULL
,	"with check" BOOLEAN DEFAULT FALSE NULL CHECK ("with check" = FALSE)
);`,
			]);
	});

	it('should use the default value and checks on mysql', () => {
		expect(AbstractSQLCompiler.mysql.compileSchema(generateModel()))
			.to.have.property('createSchema')
			.that.deep.equals([
				`\
CREATE TABLE IF NOT EXISTS "test" (
	"id" INTEGER NOT NULL CHECK ("id" > 0) PRIMARY KEY AUTO_INCREMENT
,	"with default" BOOLEAN DEFAULT TRUE NOT NULL
,	"without default" BOOLEAN DEFAULT FALSE NOT NULL
,	"with check" BOOLEAN DEFAULT FALSE NULL CHECK ("with check" = FALSE)
);`,
			]);
	});

	it('should use the default value and checks on websql', () => {
		expect(AbstractSQLCompiler.websql.compileSchema(generateModel()))
			.to.have.property('createSchema')
			.that.deep.equals([
				`\
CREATE TABLE "test" (
	"id" INTEGER NOT NULL CHECK ("id" > 0) PRIMARY KEY AUTOINCREMENT
,	"with default" BOOLEAN DEFAULT TRUE NOT NULL
,	"without default" BOOLEAN DEFAULT FALSE NOT NULL
,	"with check" BOOLEAN DEFAULT FALSE NULL CHECK ("with check" = FALSE)
);`,
			]);
	});
});
